import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const input = resolve(root, "mobile/contracts/v1/gps-policy.json");
const output = resolve(
  root,
  "mobile/shared/src/commonTest/kotlin/us/ryanshores/atlas/mobile/shared/gps/GpsPolicyGoldenFixtures.generated.kt",
);

function kotlinString(value) {
  return JSON.stringify(value);
}

function kotlinDouble(value) {
  return Number.isInteger(value) ? `${value}.0` : String(value);
}

export function renderGpsPolicyKotlin(policy) {
  const samples = policy.samples.map((sample) => `        GpsGoldenSample(
            name = ${kotlinString(sample.name)},
            accuracyMeters = ${kotlinDouble(sample.accuracyMeters)},
            ageMilliseconds = ${sample.ageMilliseconds}L,
            hasUsableFix = ${sample.hasUsableFix},
            expectedQuality = ${kotlinString(sample.expectedQuality)},
            expectedAction = ${kotlinString(sample.expectedAction)},
        ),`).join("\n");
  const movement = policy.plausibleMovementSamples.map((sample) => `        GpsGoldenMovementSample(
            distanceMeters = ${kotlinDouble(sample.distanceMeters)},
            elapsedMilliseconds = ${sample.elapsedMilliseconds}L,
            previousAccuracyMeters = ${kotlinDouble(sample.previousAccuracyMeters)},
            nextAccuracyMeters = ${kotlinDouble(sample.nextAccuracyMeters)},
            expected = ${sample.expected},
        ),`).join("\n");
  const smoothing = policy.smoothingSamples.map((sample) => `        GpsGoldenSmoothingSample(
            accuracyMeters = ${kotlinDouble(sample.accuracyMeters)},
            expectedWeight = ${kotlinDouble(sample.expectedWeight)},
        ),`).join("\n");

  return `// Generated by scripts/generate-gps-policy-kotlin.mjs from mobile/contracts/v1/gps-policy.json.
// Do not edit by hand.
package us.ryanshores.atlas.mobile.shared.gps

internal data class GpsGoldenSample(
    val name: String,
    val accuracyMeters: Double,
    val ageMilliseconds: Long,
    val hasUsableFix: Boolean,
    val expectedQuality: String,
    val expectedAction: String,
)

internal data class GpsGoldenMovementSample(
    val distanceMeters: Double,
    val elapsedMilliseconds: Long,
    val previousAccuracyMeters: Double,
    val nextAccuracyMeters: Double,
    val expected: Boolean,
)

internal data class GpsGoldenSmoothingSample(
    val accuracyMeters: Double,
    val expectedWeight: Double,
)

internal object GpsPolicyGoldenFixtures {
    const val goodAccuracyMeters = ${kotlinDouble(policy.thresholds.goodAccuracyMeters)}
    const val fairAccuracyMeters = ${kotlinDouble(policy.thresholds.fairAccuracyMeters)}
    const val maxUsableAccuracyMeters = ${kotlinDouble(policy.thresholds.maxUsableAccuracyMeters)}
    const val maxFixAgeMilliseconds = ${policy.thresholds.maxFixAgeMilliseconds}L

    val samples = listOf(
${samples}
    )

    val plausibleMovementSamples = listOf(
${movement}
    )

    val smoothingSamples = listOf(
${smoothing}
    )
}
`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const policy = JSON.parse(readFileSync(input, "utf8"));
  writeFileSync(output, renderGpsPolicyKotlin(policy));
}
